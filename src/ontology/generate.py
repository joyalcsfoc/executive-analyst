# The Genie space JSON hard-codes gold_dev identifiers (see README) — the generated
# instruction must name the kg_* functions the same way its sql_functions entries do.
GENIE_CATALOG = "gold_dev"

GENERATED_BANNER = (
    "GENERATED by src/ontology/generate.py from src/ontology/exec_analyst.ttl "
    "- do not edit by hand."
)


def local(uri: rdflib.term.URIRef | rdflib.term.BNode) -> str:
    return str(uri).rsplit("#", 1)[-1]


def literal(g: rdflib.Graph, s, p) -> str | None:
    v = g.value(s, p)
    return str(v) if v is not None else None


def literals(g: rdflib.Graph, s, p) -> list[str]:
    return [str(o) for o in g.objects(s, p)]


def ident(name: str) -> str:
    """Backtick-quote an identifier that is not a bare word.

    The five deployed metric views do not share a naming convention: revenue,
    marketing and manufacturing expose snake_case measures, while the two
    supply_chain views were rebuilt with Title Case names containing spaces
    ('Avg Days of Supply'). Those only resolve inside MEASURE() when quoted.
    """
    return name if name.replace("_", "").isalnum() else f"`{name}`"


@dataclass
class EntityClass:
    iri: rdflib.term.URIRef
    name: str
    comment: str
    table: str
    key_col: str
    name_col: str
    view: str | None
    field: str | None
    aka: list[str] = field(default_factory=list)


@dataclass
class KpiClass:
    iri: rdflib.term.URIRef
    name: str
    comment: str
    view: str
    measure: str | None
    view_field: str | None
    domain_tag: str | None
    grain_tag: str | None
    not_same_as: list[str] = field(default_factory=list)
    aka: list[str] = field(default_factory=list)


@dataclass
class GrainClass:
    """A Measurement/Event class bound only to a view + fact (defines domain/grain tags)."""

    iri: rdflib.term.URIRef
    name: str
    comment: str
    view: str
    fact: str
    domain_tag: str
    grain_tag: str


@dataclass
class AmbiguousTerm:
    iri: rdflib.term.URIRef
    name: str
    comment: str
    disambiguates_to: list[str]
    aka: list[str] = field(default_factory=list)


@dataclass
class EnumClass:
    iri: rdflib.term.URIRef
    name: str
    comment: str
    column: str | None
    values: list[str]
    aka: list[str] = field(default_factory=list)


@dataclass
class ObjectProperty:
    iri: rdflib.term.URIRef
    name: str
    comment: str
    domain_class: str
    range_class: str
    inverse_of: str | None
    edge_from: str | None
    edge_subject_key: str | None
    edge_object_key: str | None
    edge_filter: str | None


@dataclass
class Model:
    entities: list[EntityClass]
    kpis: list[KpiClass]
    grains: list[GrainClass]
    ambiguous: list[AmbiguousTerm]
    enums: list[EnumClass]
    object_properties: list[ObjectProperty]


def load_model(ttl_path: Path) -> Model:
    g = rdflib.Graph()
    g.parse(ttl_path, format="turtle")

    entities: list[EntityClass] = []
    kpis: list[KpiClass] = []
    grains: list[GrainClass] = []
    ambiguous: list[AmbiguousTerm] = []
    enums: list[EnumClass] = []
    object_properties: list[ObjectProperty] = []

    for cls in sorted(set(g.subjects(RDF.type, OWL.Class)), key=local):
        comment = literal(g, cls, RDFS.comment) or ""
        aka = literals(g, cls, EA.aka)
        table = literal(g, cls, EA.boundToTable)
        view = literal(g, cls, EA.boundToView)
        measure = literal(g, cls, EA.boundToMeasure)
        view_field = literal(g, cls, EA.boundToField)
        column = literal(g, cls, EA.boundToColumn)
        domain_tag = literal(g, cls, EA.domainTag)
        grain_tag = literal(g, cls, EA.grainTag)
        not_same_as = [local(o) for o in g.objects(cls, EA.notSameAs)]
        disambiguates_to = [local(o) for o in g.objects(cls, EA.disambiguatesTo)]

        is_ambiguous = (cls, RDFS.subClassOf, EA.AmbiguousTerm) in g
        is_kpi = (cls, RDFS.subClassOf, EA.KPI) in g
        oneof_values = _oneof_labels(g, cls)

        if is_ambiguous:
            ambiguous.append(
                AmbiguousTerm(cls, local(cls), comment, disambiguates_to, aka)
            )
        elif oneof_values:
            enums.append(EnumClass(cls, local(cls), comment, column, oneof_values, aka))
        elif is_kpi and view and measure:
            kpis.append(
                KpiClass(
                    cls, local(cls), comment, view, measure, view_field,
                    domain_tag, grain_tag, not_same_as, aka,
                )
            )
        elif table:
            entities.append(
                EntityClass(
                    cls, local(cls), comment, table,
                    literal(g, cls, EA.boundToKeyColumn) or "",
                    literal(g, cls, EA.boundToNameColumn) or "",
                    view, view_field, aka,
                )
            )
        elif view and column and domain_tag and grain_tag:
            fact = column  # ea:boundToColumn holds the bare fact table here
            grains.append(GrainClass(cls, local(cls), comment, view, fact, domain_tag, grain_tag))

    for prop in sorted(set(g.subjects(RDF.type, OWL.ObjectProperty)), key=local):
        edge_from = literal(g, prop, EA.edgeFrom)
        domain_c = g.value(prop, RDFS.domain)
        range_c = g.value(prop, RDFS.range)
        if domain_c is None or range_c is None:
            continue
        inv = g.value(prop, OWL.inverseOf)
        object_properties.append(
            ObjectProperty(
                prop, local(prop), literal(g, prop, RDFS.comment) or "",
                local(domain_c), local(range_c),
                local(inv) if inv is not None else None,
                edge_from,
                literal(g, prop, EA.edgeSubjectKey),
                literal(g, prop, EA.edgeObjectKey),
                literal(g, prop, EA.edgeFilter),
            )
        )

    return Model(entities, kpis, grains, ambiguous, enums, object_properties)


def _oneof_labels(g: rdflib.Graph, cls) -> list[str]:
    """Return rdfs:label values of an owl:oneOf enumeration's named individuals, in list order."""
    for eq in g.objects(cls, OWL.equivalentClass):
        for lst in g.objects(eq, OWL.oneOf):
            items = list(rdflib.collection.Collection(g, lst))
            return [literal(g, i, RDFS.label) or local(i) for i in items]
    return []


# ---------------------------------------------------------------------------
# tag_metric_views.sql — one ALTER VIEW per metric view, one ALTER TABLE per dim
# ---------------------------------------------------------------------------

def render_tags(model: Model) -> str:
    view_meta: dict[str, dict[str, str]] = {}
    view_terms: dict[str, list[str]] = {}
    table_terms: dict[str, list[str]] = {}

    for gr in model.grains:
        view_meta[gr.view] = {"domain": gr.domain_tag, "grain": gr.grain_tag}
        view_terms.setdefault(gr.view, [])

    for k in model.kpis:
        view_meta.setdefault(k.view, {"domain": k.domain_tag or "", "grain": k.grain_tag or ""})
        view_terms.setdefault(k.view, []).append(k.name)

    for e in model.entities:
        if e.view:
            view_terms.setdefault(e.view, []).append(e.name)
        if e.table not in table_terms:
            table_terms[e.table] = []
        table_terms[e.table].append(e.name)

    for view, meta in view_meta.items():
        if not meta.get("domain") or not meta.get("grain"):
            raise SystemExit(f"View {view!r} is missing a domain/grain tag in the TTL")

    lines = [
        "-- Tag the Executive Analyst metric views + linked dim tables for ontology wiring.",
        "-- Job param {{catalog}} expands to a quoted string (e.g. 'gold_dev'); concatenate into DDL.",
        f"-- {GENERATED_BANNER}",
        "",
        "-- --- Metric views ---",
        "",
    ]
    for view in sorted(view_meta):
        meta = view_meta[view]
        terms = ",".join(dict.fromkeys(view_terms.get(view, [])))
        lines += [
            "EXECUTE IMMEDIATE",
            f'"ALTER VIEW " || {{{{catalog}}}} || ".{view} SET TAGS (\n'
            f"  'domain' = '{meta['domain']}',\n"
            f"  'grain' = '{meta['grain']}',\n"
            f"  'kpi' = 'true',\n"
            f"  'glossary_source' = '{TTL_SOURCE}',\n"
            f"  'glossary_terms' = '{terms}'\n"
            f')";',
            "",
        ]

    lines += ["-- --- Dim tables (entity bindings) ---", ""]
    for table in sorted(table_terms):
        terms = ",".join(dict.fromkeys(table_terms[table]))
        lines += [
            "EXECUTE IMMEDIATE",
            f'"ALTER TABLE " || {{{{catalog}}}} || ".{table} SET TAGS (\n'
            f"  'glossary_source' = '{TTL_SOURCE}',\n"
            f"  'glossary_terms' = '{terms}'\n"
            f')";',
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# materialize_kg.sql — kg_nodes (entities) + kg_edges (object properties)
# ---------------------------------------------------------------------------

def render_kg(model: Model) -> str:
    entity_by_name = {e.name: e for e in model.entities}

    header = [
        "-- Executive Analyst \u2014 Delta property graph (ABox), catalog.ontology schema.",
        "-- Navigation only: KPI math stays in metrics_*. Not a Genie data source.",
        f"-- {GENERATED_BANNER}",
        "-- Schema {{catalog}}.ontology must already exist (CREATE SCHEMA IF NOT EXISTS).",
        "",
        'EXECUTE IMMEDIATE "CREATE SCHEMA IF NOT EXISTS " || {{catalog}} || ".ontology";',
        "",
        "-- --- kg_nodes: one row per entity instance, tagged with its ontology class ---",
        "",
    ]

    node_parts = []
    for e in sorted(model.entities, key=lambda x: x.name):
        node_parts.append(
            f"  SELECT\n"
            f"    '{e.name}' AS node_type,\n"
            f"    CAST({e.key_col} AS STRING) AS node_key,\n"
            f"    CAST({e.name_col} AS STRING) AS node_name\n"
            f'  FROM " || {{{{catalog}}}} || ".{e.table}'
        )
    nodes_union = "\nUNION ALL\n".join(node_parts)

    lines = header[:]

    lines.append(
        "EXECUTE IMMEDIATE\n"
        + '"CREATE OR REPLACE TABLE " || {{catalog}} || ".ontology.kg_nodes AS\n'
        + nodes_union
        + '";'
    )
    lines.append("")

    lines += ["-- --- kg_edges: one row per object property, keyed off the source fact ---", ""]

    edge_parts = []
    seen_rels: set[str] = set()
    for p in model.object_properties:
        if not p.edge_from or p.name in seen_rels:
            continue
        seen_rels.add(p.name)
        subj = entity_by_name.get(p.domain_class)
        obj = entity_by_name.get(p.range_class)
        if subj is None or obj is None:
            continue
        filt = ""
        if p.edge_filter:
            filt = " WHERE " + p.edge_filter.replace("{source}", '" || {{catalog}} || ".' + p.edge_from)
        edge_parts.append(
            f"  SELECT DISTINCT\n"
            f"    '{p.name}' AS rel,\n"
            f"    '{p.domain_class}' AS subject_type,\n"
            f"    CAST({p.edge_subject_key} AS STRING) AS subject_key,\n"
            f"    '{p.range_class}' AS object_type,\n"
            f"    CAST({p.edge_object_key} AS STRING) AS object_key\n"
            f'  FROM " || {{{{catalog}}}} || ".{p.edge_from}" || "{filt}'
        )
    edges_union = "\nUNION ALL\n".join(edge_parts)
    lines.append(
        "EXECUTE IMMEDIATE\n"
        + '"CREATE OR REPLACE TABLE " || {{catalog}} || ".ontology.kg_edges AS\n'
        + edges_union
        + '";'
    )
    return "\n".join(lines).rstrip() + "\n"


