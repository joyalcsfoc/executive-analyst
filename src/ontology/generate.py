def render_kg_queries(model: Model) -> str:
    edges_seen = []
    for p in model.object_properties:
        if p.edge_from and p.name not in {e[0] for e in edges_seen}:
            edges_seen.append((p.name, p.domain_class, p.range_class))
    lines = [
        "-- Executive Analyst knowledge graph — worked neighborhood queries.",
        "-- Run in the SQL editor against {catalog}.ontology.kg_nodes / kg_edges.",
        f"-- {GENERATED_BANNER}",
        "",
        "-- Row counts by class / relationship",
        "SELECT node_type, COUNT(*) AS n FROM {catalog}.ontology.kg_nodes GROUP BY node_type ORDER BY 1;",
        "SELECT rel, COUNT(*) AS n FROM {catalog}.ontology.kg_edges GROUP BY rel ORDER BY 1;",
        "",
        "-- Orphan edges (endpoint missing from kg_nodes -- should return 0 rows)",
        "SELECT e.* FROM {catalog}.ontology.kg_edges e",
        "LEFT JOIN {catalog}.ontology.kg_nodes s ON s.node_type = e.subject_type AND s.node_key = e.subject_key",
        "LEFT JOIN {catalog}.ontology.kg_nodes o ON o.node_type = e.object_type AND o.node_key = e.object_key",
        "WHERE s.node_key IS NULL OR o.node_key IS NULL;",
        "",
    ]
    for rel, dom, rng in edges_seen:
        lines += [
            f"-- {dom} --[{rel}]--> {rng}: sample of 10",
            f"SELECT * FROM {{catalog}}.ontology.kg_edges WHERE rel = '{rel}' LIMIT 10;",
            "",
        ]
    lines += [
        "-- Two-hop example via UC functions (once kg_functions.sql is deployed):",
        "-- SELECT * FROM {catalog}.ontology.kg_find_node('Chennai');",
        "-- SELECT * FROM {catalog}.ontology.kg_neighbors('Plant', '<plant_key>', 'plantProducesModel');",
    ]
    return "\n".join(lines).rstrip() + "\n"


