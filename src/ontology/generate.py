# genie_context.json — synonyms, enum values, not_same_as, disambiguations
# ---------------------------------------------------------------------------

def render_genie_context(model: Model) -> str:
    """Emit a structured JSON object consumed by the Genie Knowledge Store.

    Sections:
      synonyms        — ea:aka on every named class (entities, KPIs, enums, grains)
      enum_values     — owl:oneOf closed enumerations with column binding
      not_same_as     — pairs of concepts users routinely conflate
      disambiguates_to — ambiguous surface terms and their candidate concepts
    """
    synonyms: list[dict] = []
    not_same_as: list[dict] = []
    disambiguates_to: list[dict] = []
    enum_values: list[dict] = []

    # Entities
    for e in sorted(model.entities, key=lambda x: x.name):
        if e.aka:
            synonyms.append({"term": e.name, "kind": "entity", "synonyms": e.aka})

    # KPIs
    for k in sorted(model.kpis, key=lambda x: x.name):
        if k.aka:
            synonyms.append({"term": k.name, "kind": "kpi", "synonyms": k.aka})
        if k.not_same_as:
            not_same_as.append({"term": k.name, "not_same_as": k.not_same_as})

    # Enums
    for e in sorted(model.enums, key=lambda x: x.name):
        entry: dict = {"class": e.name, "values": e.values}
        if e.column:
            entry["column"] = e.column
        if e.aka:
            synonyms.append({"term": e.name, "kind": "enum", "synonyms": e.aka})
        enum_values.append(entry)

    # Ambiguous terms
    for a in sorted(model.ambiguous, key=lambda x: x.name):
        if a.aka:
            synonyms.append({"term": a.name, "kind": "ambiguous", "synonyms": a.aka})
        disambiguates_to.append({"term": a.name, "options": a.disambiguates_to})

    ctx = {
        "_comment": GENERATED_BANNER,
        "generated_from": TTL_SOURCE,
        "synonyms": synonyms,
        "enum_values": enum_values,
        "not_same_as": not_same_as,
        "disambiguates_to": disambiguates_to,
    }
    return json.dumps(ctx, indent=2, ensure_ascii=False) + "\n"


