#!/usr/bin/env python3
"""Generate every downstream ontology artifact from exec_analyst.ttl.

exec_analyst.ttl is the single source of truth (see its rdfs:comment on the
owl:Ontology node). This script reads it and regenerates:

  src/metric_views/tag_metric_views.sql   UC tags (domain/grain/kpi/glossary_terms)
  src/ontology/materialize_kg.sql         ontology.kg_nodes / kg_edges (ABox)
  src/ontology/grant_kg.sql               GRANT USAGE/SELECT on the KG schema
  src/ontology/kg_functions.sql           UC SQL functions for graph traversal
  src/ontology/kg_queries.sql             worked neighborhood queries (SQL editor)
  ontology_reference.html                 browsable class/property reference

Nothing below should be hand-edited; change exec_analyst.ttl and re-run.

Usage (from repo root):
  python src/ontology/generate.py
  python src/ontology/generate.py --check   # exit 1 if any output is stale
"""

